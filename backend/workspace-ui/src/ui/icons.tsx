export type IconName = keyof typeof GLYPHS;

export function Svg({ name, size }: { name: IconName; size: number }) {
  return (
    <svg
      viewBox="0 0 24 24" width={size} height={size} fill="none" stroke="currentColor"
      strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true"
    >
      {GLYPHS[name]}
    </svg>
  );
}

/** The legacy `icon(name, size)`: a `.icon` span around the drawing. */
export function Icon({ name, size, className = 'icon' }: { name: IconName; size: number; className?: string }) {
  return <span className={className}><Svg name={name} size={size} /></span>;
}

/** The legacy `iconbox(name)`: the boxed 17px glyph a row leads with. */
export function IconBox({ name, dim }: { name: IconName; dim?: boolean }) {
  return <Icon name={name} size={17} className={dim ? 'iconbox dim' : 'iconbox'} />;
}

/** The `ft-*` families the stylesheet paints: the states a row can be in,
 *  then the file-kind hues the tree and the chat's file rows share. */
export type IconTint =
  | '' | 'act' | 'ok' | 'mut' | 'warn' | 'dir' | 'note'
  | 'media' | 'secret' | 'js' | 'ts' | 'web' | 'style' | 'doc' | 'code' | 'shell';

/** The legacy `typeIcon({ glyph, tint })`: a 20px glyph with a `.ft-*` tint. */
export function TypeIcon({ glyph, tint = '' }: { glyph: IconName; tint?: IconTint }) {
  return <Icon name={glyph} size={20} className={`icon ft${tint ? ` ft-${tint}` : ''}`} />;
}
